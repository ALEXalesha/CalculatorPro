out = []
for name, keys, value, extra in cases:
    case = {"name": name, "keys": keys}
    if value is not None:
        assert MIN <= value <= MAX, name
        case.update(views(value))
    case.update(extra)
    if "error" not in case:
        case["error"] = None
    out.append(case)

target = Path(__file__).with_name("programmer.json")
target.parent.mkdir(exist_ok=True)
target.write_text(json.dumps(out, ensure_ascii=False, indent=1) + "\n", encoding="utf-8", newline="\n")
