import json
from pathlib import Path

M = 1 << 64


def grp(s, size):
    sign = "-" if s.startswith("-") else ""
    s = s.lstrip("-")
    out = ""
    for i, ch in enumerate(s):
        if i > 0 and (len(s) - i) % size == 0:
            out += " "
        out += ch
    return sign + out


def views(v):
    u = v % M
    return {
        "hex": grp(format(u, "X"), 4),
        "dec": grp(str(v), 3),
        "oct": grp(format(u, "o"), 3),
        "bin": grp(format(u, "b"), 4),
    }


